"""Generate Android regex constants from the same JSON used directly by Python and JS."""
import json
from pathlib import Path
import sys
R=Path(__file__).resolve().parents[1]
policy=json.loads((R/'mcp/interaction_policy.json').read_text(encoding='utf-8'))
source='package kira.phoneuse.data\n\n// Generated by audit/sync_interaction_policy.py; edit mcp/interaction_policy.json.\ninternal object InteractionPolicy {\n'
for key in ('risky','sensitive'):
    assert '$' not in policy[key] and '"""' not in policy[key]
    source+=f'    val {key} = Regex("""{policy[key]}""", RegexOption.IGNORE_CASE)\n'
source+='}\n'
p=R/'server/src/main/java/kira/phoneuse/data/InteractionPolicy.kt'
if '--check' in sys.argv:
    assert p.read_text(encoding='utf-8')==source,'InteractionPolicy.kt must be regenerated'
else:p.write_text(source,encoding='utf-8',newline='\n')
